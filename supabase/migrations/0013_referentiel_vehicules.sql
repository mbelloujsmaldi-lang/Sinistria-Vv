-- ============================================================
-- Sinistria-VV — 0013 : référentiel Marques & Modèles (Sprint 14)
--
-- Reprend le référentiel de l'ancien système (sélecteur marque -> modèle,
-- suggestion de la valeur à neuf) avec, cette fois, des droits appliqués
-- par la base et non seulement par l'interface :
--   - lecture : tout profil existant ET actif (est_profil_actif(), 0012) ;
--   - ajout d'une marque ou d'un modèle (« à la volée ») : tout profil actif,
--     mais un modèle ajouté par un non-éditeur ne peut pas porter de prix VN ;
--   - renommer, supprimer, éditer vn_reference : responsable et au-dessus
--     (current_role_niveau() >= 5, nul pour un profil inactif ou absent).
--
-- Unicité insensible à la casse, aux espaces de bord : comme la
-- normalisation (trim + minuscules) de l'ancien système.
--
-- Les colonnes vv_calculations.marque / .modele restent du texte libre
-- (instantané de ce qui a été saisi, pas de clé étrangère, pas de reprise).
--
-- Seed : 44 marques / 322 modèles, générés par programme depuis la
-- constante VSEED de l'ancien Index.html (aucun prix VN dans la source).
-- ============================================================

create table vehicule_marques (
  id uuid primary key default gen_random_uuid(),
  nom text not null unique,
  constraint vehicule_marques_nom_propre check (nom = btrim(nom) and nom <> '')
);
create unique index vehicule_marques_nom_norm on vehicule_marques (lower(btrim(nom)));

create table vehicule_modeles (
  id uuid primary key default gen_random_uuid(),
  marque_id uuid not null references vehicule_marques(id) on delete cascade,
  nom text not null,
  vn_reference numeric(12,2),
  unique (marque_id, nom),
  constraint vehicule_modeles_nom_propre check (nom = btrim(nom) and nom <> ''),
  constraint vehicule_modeles_vn_positive check (vn_reference is null or vn_reference > 0)
);
create unique index vehicule_modeles_marque_nom_norm on vehicule_modeles (marque_id, lower(btrim(nom)));

alter table vehicule_marques enable row level security;
alter table vehicule_modeles enable row level security;

-- Lecture
create policy "vehicule_marques_select" on vehicule_marques
  for select using (est_profil_actif());
create policy "vehicule_modeles_select" on vehicule_modeles
  for select using (est_profil_actif());

-- Ajout à la volée : tout profil actif
create policy "vehicule_marques_insert" on vehicule_marques
  for insert with check (est_profil_actif());
create policy "vehicule_modeles_insert" on vehicule_modeles
  for insert with check (
    est_profil_actif()
    and (vn_reference is null or current_role_niveau() >= role_niveau('responsable'))
  );

-- Modification et suppression : responsable et au-dessus
create policy "vehicule_marques_update" on vehicule_marques
  for update using (current_role_niveau() >= role_niveau('responsable'))
  with check (current_role_niveau() >= role_niveau('responsable'));
create policy "vehicule_marques_delete" on vehicule_marques
  for delete using (current_role_niveau() >= role_niveau('responsable'));
create policy "vehicule_modeles_update" on vehicule_modeles
  for update using (current_role_niveau() >= role_niveau('responsable'))
  with check (current_role_niveau() >= role_niveau('responsable'));
create policy "vehicule_modeles_delete" on vehicule_modeles
  for delete using (current_role_niveau() >= role_niveau('responsable'));

