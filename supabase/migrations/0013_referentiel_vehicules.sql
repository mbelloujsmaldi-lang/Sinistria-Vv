-- Garde-fou : la migration entière est annulée si le seed n'est pas exact.
do $$
declare nb_marques int; nb_modeles int;
begin
  select count(*) into nb_marques from vehicule_marques;
  select count(*) into nb_modeles from vehicule_modeles;
  if nb_marques <> 44 or nb_modeles <> 322 then
    raise exception 'Seed référentiel inexact : % marques / % modèles (attendu 44 / 322)', nb_marques, nb_modeles;
  end if;
end $$;
